def ensure_default_buildings(sync_conn):
    """
    Ensures all 110 Buildings/Locations from Drawing A-02 exist in the database.
    Updates existing records (1-23) to official master titles and inserts missing records (24-110).
    Preserves device foreign keys and existing building IDs.
    """
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    for b_id, code, name, desc in BUILDINGS_DATA:
        existing = sync_conn.execute(
            text("SELECT id FROM buildings WHERE id = :id"),
            {"id": b_id}
        ).fetchone()

        if existing:
            # Update building name, code, description to match Drawing A-02
            sync_conn.execute(
                text("UPDATE buildings SET name = :name, code = :code, description = :desc WHERE id = :id"),
                {"id": b_id, "name": name, "code": code, "desc": desc}
            )
        else:
            # Insert new building with exact ID
            sync_conn.execute(
                text("INSERT INTO buildings (id, name, code, description, created_at) VALUES (:id, :name, :code, :desc, :now)"),
                {"id": b_id, "name": name, "code": code, "desc": desc, "now": now_str}
            )
